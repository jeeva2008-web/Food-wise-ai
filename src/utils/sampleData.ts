export function generateSampleRedistributions(records: FoodRecord[]): RedistributionRecord[] {
  const surplusRecords = records.filter(
    (r) => r.quantityRedistributedKg > 0 || r.status === 'Surplus Active' || r.status === 'Under Review'
  );

  const recipients = [
    'Rathinam Hostel Block 4 Student Night Pantry',
    'Coimbatore Shanti Shelter Kitchen (Echanari)',
    'Rathinam TechZone EcoCare Network',
    'Rathinam Staff Mess & Campus Security Evening Shift',
  ];

  return surplusRecords.slice(0, 8).map((record, idx) => {
    const isCompleted = record.quantityRedistributedKg > 0;
    const proposed = recipients[idx % recipients.length];

    return {
      id: `REDIST-${500 + idx + 1}`,
      recordId: record.id,
      foodName: record.foodName,
      category: record.category,
      quantityAvailableKg: record.quantityRemainingKg,
      preparationDateTime: record.preparationDateTime,
      useByDateTime: record.useByDateTime,
      storageCondition: record.storageCondition,
      proposedRecipient: proposed,
      recipientContact: '+1 (555) 019-482' + idx,
      reviewStatus: isCompleted ? 'Redistributed' : idx % 2 === 0 ? 'Under Review' : 'Approved',
      approvedBy: isCompleted || idx % 2 !== 0 ? 'Prof. A. Sharma (Canteen Food Safety Supervisor)' : undefined,
      safetyChecklist: {
        tempVerified: true,
        sensoryTestPassed: true,
        packagedHygiene: true,
        withinTimeWindow: true,
      },
      quantityApprovedKg: isCompleted ? record.quantityRedistributedKg : Math.min(record.quantityRemainingKg, 8.0),
      quantityRedistributedKg: record.quantityRedistributedKg,
      quantityRemainingKg: Math.max(0, record.quantityRemainingKg - record.quantityRedistributedKg),
      actionNotes: isCompleted
        ? `Transferred in sanitized thermal bins. Received by ${proposed}.`
        : 'Inspected by chef on duty. Awaiting dispatch vehicle.',
      createdAt: record.preparationDateTime,
      updatedAt: record.preparationDateTime,
    };
  });
}
